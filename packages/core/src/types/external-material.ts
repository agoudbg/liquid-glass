import type { CornerRadii, RectLike } from './common';
import type { AutomaticBackgroundColorMode } from './context';

/**
 * Transform values delegated with an externally rendered material.
 */
export interface ExternalMaterialTransform {
  /** Horizontal scale. */
  scaleX: number;
  /** Vertical scale. */
  scaleY: number;
  /** Horizontal translation in pixels. */
  translateX: number;
  /** Vertical translation in pixels. */
  translateY: number;
}

/**
 * Complete configuration sent to a nested context for delegated rendering.
 */
export interface ExternalMaterialConfig {
  /** Material bounds in viewport coordinates. */
  clientRect: RectLike;
  /** Material corner radii. */
  borderRadius: CornerRadii;
  /** Frosted-glass blur amount. */
  blur: number;
  /** Optical glass thickness. */
  thickness: number;
  /** Index of refraction. */
  refractIndex: number;
  /** Refraction displacement multiplier. */
  refractIntensity: number;
  /** Chromatic dispersion strength. */
  dispersion: number;
  /** Current interaction and CSS transform. */
  transform: ExternalMaterialTransform;
}

/** Lifecycle handle for one material delegated to another context. */
export interface ExternalMaterialHandle {
  /** Stable identifier generated by the accepting proxy context. */
  readonly id: string;
  /** Whether this delegated registration has been released. */
  readonly destroyed: boolean;
  /** Apply partial configuration changes. */
  update(changes: Partial<ExternalMaterialConfig>): void;
  /** Subscribe to sampled backdrop feedback. */
  onFeedback(callback: (feedback: ExternalMaterialFeedback) => void): () => void;
  /** Idempotently remove this material from the proxy context. */
  destroy(): void;
}

/**
 * Backdrop-derived feedback returned by the rendering context.
 */
export interface ExternalMaterialFeedback {
  /** Sampled backdrop brightness class. */
  themeColorMode: AutomaticBackgroundColorMode;
  /** Optional average luma in the inclusive 0-255 range. */
  averageLuminance?: number;
}

/**
 * API exposed by a context that accepts externally owned materials.
 */
export interface ProxyInterface {
  /** Register a delegated material and return its lifecycle handle. */
  registerExternalMaterial(config: ExternalMaterialConfig): ExternalMaterialHandle;
  /** Read the proxy container bounds in viewport coordinates. */
  getContainerRect(): DOMRectReadOnly | null;
  /** Read the proxy container scroll position. */
  getScrollPosition(): { x: number; y: number };
}

/**
 * Public name used by material configuration for a delegation target.
 */
export type ProxyTargetInterface = ProxyInterface;

/**
 * Coordinates resolved for rendering an external material in a proxy canvas.
 */
export interface ExternalMaterialCanvasCoords {
  /** Destination horizontal offset in CSS pixels. */
  destX: number;
  /** Destination vertical offset in CSS pixels. */
  destY: number;
  /** Source horizontal offset in CSS pixels. */
  srcX: number;
  /** Source vertical offset in CSS pixels. */
  srcY: number;
  /** Material width in CSS pixels. */
  width: number;
  /** Material height in CSS pixels. */
  height: number;
  /** Whether any part of the material intersects the proxy bounds. */
  isVisible: boolean;
}
